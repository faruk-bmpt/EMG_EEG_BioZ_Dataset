#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
===============================================================================
SHA-256 CHECKSUM GENERATION — DATASET V1.0
===============================================================================

Purpose
-------
Generate cryptographic SHA-256 checksums for the formally frozen Dataset V1.0.

This stage is READ-ONLY with respect to:
    - raw data
    - processed signal data
    - metadata
    - annotations
    - modality views

It does NOT:
    - rerun preprocessing
    - perform feature extraction
    - perform machine learning
    - generate fusion data
    - modify or rename recordings
    - modify raw folders

Outputs
-------
05_QC/DATASET_FREEZE/SHA256/
    SHA256SUMS_V1.0.csv
    SHA256SUMS_V1.0.txt
    SHA256_CHECKSUM_FINAL_REPORT.json
===============================================================================
"""

from __future__ import annotations

import csv
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path


# =============================================================================
# DATASET ROOT
# =============================================================================

ROOT = Path(
    "/mnt/f/Faruk/OFS_Paper_Work/Data_Set_Paper_Work/"
    "EEG_EMG_BIOZ_DATASET"
).resolve()

FREEZE = ROOT / "05_QC" / "DATASET_FREEZE"

SENTINEL = (
    FREEZE /
    "_DATASET_V1.0_FROZEN.json"
)

OUTPUT_DIR = (
    FREEZE /
    "SHA256"
)

CSV_OUTPUT = (
    OUTPUT_DIR /
    "SHA256SUMS_V1.0.csv"
)

TXT_OUTPUT = (
    OUTPUT_DIR /
    "SHA256SUMS_V1.0.txt"
)

REPORT_OUTPUT = (
    OUTPUT_DIR /
    "SHA256_CHECKSUM_FINAL_REPORT.json"
)


# =============================================================================
# DATASET VERSION
# =============================================================================

DATASET_VERSION = "V1.0"

PROTOCOL_VERSION = (
    "SHA256-CHECKSUM-DATASET-V1.0-FINAL"
)


# =============================================================================
# UTILITY
# =============================================================================

def utc_now():
    return datetime.now(timezone.utc).isoformat()


def sha256_file(path: Path) -> str:

    sha = hashlib.sha256()

    with path.open("rb") as f:

        for chunk in iter(
            lambda: f.read(1024 * 1024),
            b"",
        ):

            sha.update(chunk)

    return sha.hexdigest()


# =============================================================================
# EXCLUSION POLICY
# =============================================================================

# The Freeze directory contains the freeze report itself and the checksum
# outputs generated by this stage. These files are excluded from the checksum
# catalog to prevent circular/self-referential checksums.

EXCLUDED_PREFIXES = [
    Path("05_QC") / "DATASET_FREEZE",
]


def is_excluded(relative_path: Path) -> bool:

    for prefix in EXCLUDED_PREFIXES:

        if (
            relative_path == prefix
            or prefix in relative_path.parents
        ):
            return True

    return False


# =============================================================================
# VERIFY FREEZE STATE
# =============================================================================

def verify_freeze():

    if not ROOT.exists():

        raise FileNotFoundError(
            f"Dataset root not found: {ROOT}"
        )

    if not SENTINEL.exists():

        raise FileNotFoundError(
            f"Freeze sentinel not found: {SENTINEL}"
        )

    with SENTINEL.open(
        "r",
        encoding="utf-8",
    ) as f:

        sentinel = json.load(f)

    if sentinel.get("status") != "FROZEN":

        raise RuntimeError(
            "Dataset is not formally frozen. "
            "Checksum generation aborted."
        )

    return sentinel


# =============================================================================
# COLLECT DATASET FILES
# =============================================================================

def collect_files():

    files = []

    for path in ROOT.rglob("*"):

        if not path.is_file():
            continue

        relative_path = path.relative_to(ROOT)

        if is_excluded(relative_path):
            continue

        files.append(
            (
                relative_path.as_posix(),
                path,
            )
        )

    files.sort(
        key=lambda x: x[0]
    )

    return files


# =============================================================================
# GENERATE CHECKSUMS
# =============================================================================

def generate_checksums(files):

    rows = []

    for relative_path, path in files:

        digest = sha256_file(path)

        rows.append(
            {
                "relative_path": relative_path,
                "size_bytes": path.stat().st_size,
                "sha256": digest,
            }
        )

    return rows


# =============================================================================
# WRITE CSV CHECKSUM MANIFEST
# =============================================================================

def write_csv(rows):

    with CSV_OUTPUT.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=[
                "relative_path",
                "size_bytes",
                "sha256",
            ],
        )

        writer.writeheader()

        writer.writerows(rows)


# =============================================================================
# WRITE STANDARD SHA256 TEXT FILE
# =============================================================================

def write_text(rows):

    with TXT_OUTPUT.open(
        "w",
        encoding="utf-8",
    ) as f:

        for row in rows:

            f.write(
                f"{row['sha256']}  "
                f"{row['relative_path']}\n"
            )


# =============================================================================
# CHECKSUM CATALOG HASH
# =============================================================================

def calculate_catalog_hash(rows):

    catalog_hash = hashlib.sha256()

    for row in rows:

        catalog_hash.update(
            (
                f"{row['sha256']}  "
                f"{row['relative_path']}\n"
            ).encode("utf-8")
        )

    return catalog_hash.hexdigest()


# =============================================================================
# WRITE FINAL REPORT
# =============================================================================

def write_report(
    rows,
    catalog_sha256,
    sentinel,
):

    report = {

        "dataset_version":
            DATASET_VERSION,

        "protocol_version":
            PROTOCOL_VERSION,

        "generated_at_utc":
            utc_now(),

        "dataset_root":
            str(ROOT),

        "freeze_sentinel":
            str(SENTINEL.relative_to(ROOT)),

        "freeze_status_verified":
            True,

        "checksum_algorithm":
            "SHA-256",

        "files_hashed":
            len(rows),

        "read_only":
            True,

        "raw_data_modified":
            False,

        "processed_data_modified":
            False,

        "preprocessing_rerun":
            False,

        "feature_extraction":
            False,

        "machine_learning":
            False,

        "fusion_generation":
            False,

        "checksum_manifest":
            str(
                CSV_OUTPUT.relative_to(ROOT)
            ),

        "checksum_text":
            str(
                TXT_OUTPUT.relative_to(ROOT)
            ),

        "checksum_catalog_sha256":
            catalog_sha256,

        "excluded_paths": [
            "05_QC/DATASET_FREEZE/"
        ],

        "freeze_sentinel_status":
            sentinel.get("status"),

        "freeze_protocol_version":
            sentinel.get("protocol_version"),
    }

    with REPORT_OUTPUT.open(
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            report,
            f,
            indent=2,
            ensure_ascii=False,
        )


# =============================================================================
# MAIN
# =============================================================================

def main():

    print()
    print("=" * 78)
    print("SHA-256 CHECKSUM GENERATION — DATASET V1.0")
    print("=" * 78)

    print(
        f"Dataset root        : {ROOT}"
    )

    print(
        f"Protocol            : {PROTOCOL_VERSION}"
    )

    print("=" * 78)

    # ------------------------------------------------------------
    # Freeze verification
    # ------------------------------------------------------------

    sentinel = verify_freeze()

    print(
        "Freeze status        : VERIFIED"
    )

    print(
        f"Sentinel status      : "
        f"{sentinel.get('status')}"
    )

    # ------------------------------------------------------------
    # Collect files
    # ------------------------------------------------------------

    files = collect_files()

    print(
        f"Files selected       : {len(files)}"
    )

    print(
        "Raw/processed data   : READ-ONLY"
    )

    print("=" * 78)

    # ------------------------------------------------------------
    # Generate checksums
    # ------------------------------------------------------------

    rows = generate_checksums(files)

    # ------------------------------------------------------------
    # Create checksum output directory
    # ------------------------------------------------------------

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ------------------------------------------------------------
    # Write outputs
    # ------------------------------------------------------------

    write_csv(rows)

    write_text(rows)

    catalog_sha256 = (
        calculate_catalog_hash(rows)
    )

    write_report(
        rows,
        catalog_sha256,
        sentinel,
    )

    # ------------------------------------------------------------
    # Final summary
    # ------------------------------------------------------------

    print(
        f"Files hashed        : {len(rows)}"
    )

    print(
        "Algorithm            : SHA-256"
    )

    print(
        "Raw data modified    : False"
    )

    print(
        "Processed modified   : False"
    )

    print(
        "Preprocessing rerun  : False"
    )

    print(
        "Feature extraction   : False"
    )

    print(
        "Machine learning     : False"
    )

    print(
        "Fusion generation    : False"
    )

    print("-" * 78)

    print(
        f"CSV manifest         : {CSV_OUTPUT}"
    )

    print(
        f"Text checksums       : {TXT_OUTPUT}"
    )

    print(
        f"Final report         : {REPORT_OUTPUT}"
    )

    print(
        f"Catalog SHA-256      : {catalog_sha256}"
    )

    print("=" * 78)
    print(
        "SHA-256 CHECKSUM GENERATION: COMPLETE"
    )
    print("=" * 78)


if __name__ == "__main__":
    main()
